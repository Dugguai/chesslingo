// हर सेक्शन में 125 lessons generate करते हैं
export function getAllLessons(section) {
  const list = [...section.lessons];
  while (list.length < 125) {
    const n = list.length + 1;
    const base = section.lessons[(n - 1) % section.lessons.length];
    list.push({
      ...base,
      id: n,
      title: `${section.subtitle} अभ्यास ${n}`,
      oscarIntro: base.oscarIntro || 'Let\'s practice this position!',
    });
  }
  return list;
}

